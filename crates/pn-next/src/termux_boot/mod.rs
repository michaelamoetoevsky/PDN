//! Termux:Boot Integration Module
//! Provides auto-start capabilities for services at Termux boot

use anyhow::{Context, Result};
use std::fs;
use std::path::{Path, PathBuf};
use tokio::fs as async_fs;
use tracing::{debug, info, warn};

/// Termux:Boot configuration
#[derive(Debug, Clone, serde::Deserialize, serde::Serialize)]
pub struct TermuxBootConfig {
    /// Enable Termux:Boot integration
    pub enabled: bool,
    /// Path to Termux:Boot scripts directory
    pub boot_scripts_dir: PathBuf,
    /// Script name prefix
    pub script_prefix: String,
    /// Services to auto-start at boot
    pub auto_start_services: Vec<String>,
    /// Delay before starting services (seconds)
    pub start_delay_secs: u64,
    /// Whether to start services in background
    pub background: bool,
}

impl Default for TermuxBootConfig {
    fn default() -> Self {
        Self {
            enabled: true,
            boot_scripts_dir: PathBuf::from("~/.termux/boot").expand(),
            script_prefix: "pdn-".to_string(),
            auto_start_services: Vec::new(),
            start_delay_secs: 5,
            background: true,
        }
    }
}

/// Termux:Boot manager for service auto-start
pub struct TermuxBootManager {
    config: TermuxBootConfig,
    services_dir: PathBuf,
}

impl TermuxBootManager {
    /// Create a new Termux:Boot manager
    pub fn new(config: TermuxBootConfig) -> Self {
        let services_dir = config.boot_scripts_dir.join("services");
        Self {
            config,
            services_dir,
        }
    }

    /// Initialize Termux:Boot integration
    pub async fn initialize(&self) -> Result<()> {
        if !self.config.enabled {
            info!("Termux:Boot integration disabled");
            return Ok(());
        }

        // Expand home directory
        let boot_dir =
            shellexpand::tilde(&self.config.boot_scripts_dir.to_string_lossy()).into_owned();
        let boot_path = PathBuf::from(&boot_dir);

        // Create boot scripts directory
        async_fs::create_dir_all(&boot_path)
            .await
            .context("Failed to create Termux:Boot scripts directory")?;

        // Create services subdirectory
        async_fs::create_dir_all(&self.services_dir)
            .await
            .context("Failed to create services directory")?;

        // Create main boot script
        self.create_boot_script(&boot_path).await?;

        info!(
            "Termux:Boot integration initialized at {}",
            boot_path.display()
        );
        Ok(())
    }

    /// Create the main boot script
    async fn create_boot_script(&self, boot_dir: &Path) -> Result<()> {
        let script_name = format!("{}start-services.sh", self.config.script_prefix);
        let script_path = boot_dir.join(&script_name);

        let script_content = self.generate_boot_script();

        async_fs::write(&script_path, script_content)
            .await
            .context("Failed to write boot script")?;

        // Make executable
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mut perms = fs::metadata(&script_path)?.permissions();
            perms.set_mode(0o755);
            fs::set_permissions(&script_path, perms)?;
        }

        debug!("Created boot script: {}", script_path.display());
        Ok(())
    }

    /// Generate boot script content
    fn generate_boot_script(&self) -> String {
        let services = self.config.auto_start_services.join(" ");
        let delay = self.config.start_delay_secs;
        let background = if self.config.background { "&" } else { "" };

        format!(
            r#"#!/bin/sh
# PDN Termux:Boot Auto-Start Script
# Generated by PDN Service Orchestration Platform
# DO NOT EDIT MANUALLY - Regenerate via PDN CLI

# Wait for system to settle
sleep {}

# Start PDN daemon if not running
if ! pgrep -f "podnext daemon" > /dev/null; then
    echo "Starting PDN daemon..."
    podnext daemon start {} &
fi

# Wait for daemon to be ready
sleep 3

# Start configured services
for service in {}; do
    echo "Starting service: $service"
    podnext service start "$service" {} &
done

# Wait for all background jobs
wait

echo "PDN Termux:Boot auto-start completed"
"#,
            delay, background, services, background
        )
    }

    /// Add a service to auto-start list
    pub async fn add_auto_start_service(&mut self, service_name: &str) -> Result<()> {
        if !self
            .config
            .auto_start_services
            .contains(&service_name.to_string())
        {
            self.config
                .auto_start_services
                .push(service_name.to_string());
            self.regenerate_boot_script().await?;
        }
        Ok(())
    }

    /// Remove a service from auto-start list
    pub async fn remove_auto_start_service(&mut self, service_name: &str) -> Result<()> {
        self.config
            .auto_start_services
            .retain(|s| s != service_name);
        self.regenerate_boot_script().await?;
        Ok(())
    }

    /// Get list of auto-start services
    pub fn get_auto_start_services(&self) -> &[String] {
        &self.config.auto_start_services
    }

    /// Regenerate boot script after config changes
    async fn regenerate_boot_script(&self) -> Result<()> {
        let boot_dir =
            shellexpand::tilde(&self.config.boot_scripts_dir.to_string_lossy()).into_owned();
        let boot_path = PathBuf::from(&boot_dir);
        self.create_boot_script(&boot_path).await
    }

    /// Generate individual service boot script
    pub async fn create_service_script(
        &self,
        service_name: &str,
        command: &[String],
    ) -> Result<()> {
        let script_name = format!("{}{}.sh", self.config.script_prefix, service_name);
        let script_path = self.services_dir.join(&script_name);

        let cmd = command.join(" ");
        let script_content = format!(
            r#"#!/bin/sh
# PDN Service Boot Script: {}
# Generated by PDN Service Orchestration Platform

exec {} >> ~/.termux/boot/pdn-{}.log 2>&1
"#,
            service_name, cmd, service_name
        );

        async_fs::write(&script_path, script_content)
            .await
            .context("Failed to write service boot script")?;

        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mut perms = fs::metadata(&script_path)?.permissions();
            perms.set_mode(0o755);
            fs::set_permissions(&script_path, perms)?;
        }

        debug!("Created service boot script: {}", script_path.display());
        Ok(())
    }

    /// Check if Termux:Boot is available
    pub fn is_available() -> bool {
        let boot_dir = shellexpand::tilde("~/.termux/boot").into_owned();
        Path::new(&boot_dir).exists()
    }

    /// Get boot script path
    pub fn boot_script_path(&self) -> PathBuf {
        let boot_dir =
            shellexpand::tilde(&self.config.boot_scripts_dir.to_string_lossy()).into_owned();
        PathBuf::from(boot_dir).join(format!("{}start-services.sh", self.config.script_prefix))
    }
}

/// Trait for path expansion
trait ExpandPath {
    fn expand(self) -> PathBuf;
}

impl ExpandPath for PathBuf {
    fn expand(self) -> PathBuf {
        let expanded = shellexpand::tilde(&self.to_string_lossy()).into_owned();
        PathBuf::from(expanded)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::tempdir;

    #[tokio::test(flavor = "multi_thread")]
    async fn test_termux_boot_manager_creation() {
        let config = TermuxBootConfig::default();
        let manager = TermuxBootManager::new(config);
        assert!(manager.config.enabled);
    }

    #[tokio::test(flavor = "multi_thread")]
    async fn test_boot_script_generation() {
        let config = TermuxBootConfig {
            auto_start_services: vec!["web-server".to_string(), "database".to_string()],
            start_delay_secs: 10,
            background: true,
            ..Default::default()
        };
        let manager = TermuxBootManager::new(config);
        let script = manager.generate_boot_script();

        assert!(script.contains("web-server"));
        assert!(script.contains("database"));
        assert!(script.contains("sleep 10"));
        assert!(script.contains("podnext daemon start"));
    }
}
